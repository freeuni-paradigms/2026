constexpr const char* kGreen = "\033[32m";
constexpr const char* kRed = "\033[31m";
constexpr const char* kReset = "\033[0m";

struct ExpectedCase {
  std::mt19937::result_type seed;
  const char* const* tokens;
  std::size_t size;
};

Grammar LoadGrammar(const std::string& path) {
  std::ifstream input(path);
  if (!input && path.rfind("../", 0) == 0) {
    input.clear();
    input.open(path.substr(3));
  }
  if (!input) {
    return {};
  }
  return ReadGrammar(input);
}

std::vector<std::string> ExpectedVector(const ExpectedCase& expected) {
  return std::vector<std::string>(expected.tokens,
                                  expected.tokens + expected.size);
}

std::string FormatToken(const std::string& value) {
  std::string result = "\"";
  for (char ch : value) {
    switch (ch) {
      case '\\': result += "\\\\"; break;
      case '"': result += "\\\""; break;
      case '\n': result += "\\n"; break;
      case '\r': result += "\\r"; break;
      case '\t': result += "\\t"; break;
      default: result += ch; break;
    }
  }
  result += '"';
  return result;
}

std::string FormatVector(const std::vector<std::string>& values,
                         std::size_t mismatch, const char* highlight_color) {
  std::string result = "[";
  for (std::size_t i = 0; i < values.size(); ++i) {
    if (i != 0) {
      result += ", ";
    }
    if (i == mismatch && highlight_color[0] != '\0') {
      result += highlight_color;
      result += FormatToken(values[i]);
      result += kReset;
    } else {
      result += FormatToken(values[i]);
    }
  }
  result += "]";
  return result;
}

bool UseAnsiColors() {
  if (std::getenv("NO_COLOR") != nullptr) {
    return false;
  }
  return std::getenv("FORCE_COLOR") != nullptr || isatty(STDOUT_FILENO);
}

void LogDifference(std::size_t mismatch,
                   const std::vector<std::string>& expected,
                   const std::vector<std::string>& actual, bool color) {
  const char* expected_color = color ? kGreen : "";
  const char* actual_color = color ? kRed : "";
  const char* reset = color ? kReset : "";

  LOG_INFO("first difference at index %zu", mismatch);
  if (mismatch < expected.size()) {
    const std::string token = FormatToken(expected[mismatch]);
    LOG_INFO("  expected[%zu]: %s%s%s", mismatch, expected_color,
             token.c_str(), reset);
  } else {
    LOG_INFO("  expected[%zu]: %s<end of vector>%s", mismatch,
             expected_color, reset);
  }
  if (mismatch < actual.size()) {
    const std::string token = FormatToken(actual[mismatch]);
    LOG_INFO("  actual[%zu]:   %s%s%s", mismatch, actual_color,
             token.c_str(), reset);
  } else {
    LOG_INFO("  actual[%zu]:   %s<end of vector>%s", mismatch,
             actual_color, reset);
  }
}

void Fail(Test* test, const char* fixture, std::mt19937::result_type seed,
          const char* reason, std::size_t mismatch,
          const std::vector<std::string>& expected,
          const std::vector<std::string>& actual) {
  test->success = false;
  std::snprintf(test->error, sizeof(test->error), "%s seed %u: %s",
                fixture, static_cast<unsigned>(seed), reason);
  const bool color = UseAnsiColors();
  const std::string expected_text =
      FormatVector(expected, mismatch, color ? kGreen : "");
  const std::string actual_text =
      FormatVector(actual, mismatch, color ? kRed : "");
  LOG_INFO("%s", test->error);
  LogDifference(mismatch, expected, actual, color);
  LOG_INFO("expected vector: %s", expected_text.c_str());
  LOG_INFO("actual vector: %s", actual_text.c_str());
}

void RunFixture(Test* test, const char* fixture, const char* path,
                const ExpectedCase (&cases)[3]) {
  const Grammar grammar = LoadGrammar(path);
  if (grammar.find("<start>") == grammar.end()) {
    Fail(test, fixture, cases[0].seed, "missing <start> definition", 0,
         ExpectedVector(cases[0]), {});
    return;
  }

  for (const ExpectedCase& expected : cases) {
    RandomGenerator random(expected.seed);
    std::vector<std::string> output;
    ExpandSymbol("<start>", grammar, random, output);

    const std::vector<std::string> expected_output = ExpectedVector(expected);
    if (output != expected_output) {
      std::size_t mismatch = 0;
      while (mismatch < output.size() && mismatch < expected_output.size() &&
             output[mismatch] == expected_output[mismatch]) {
        ++mismatch;
      }
      char reason[128];
      if (mismatch < output.size() && mismatch < expected_output.size()) {
        std::snprintf(reason, sizeof(reason), "token %zu differs", mismatch);
      } else {
        std::snprintf(reason, sizeof(reason),
                      "vector size differs: expected %zu, actual %zu",
                      expected_output.size(), output.size());
      }
      Fail(test, fixture, expected.seed, reason, mismatch,
           expected_output, output);
      return;
    }
  }
}

